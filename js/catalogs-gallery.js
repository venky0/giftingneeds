document.addEventListener('DOMContentLoaded', function() {
  const container = document.getElementById('catalogs-grid');
  const searchInput = document.getElementById('catalog-search');
  const categoryFilters = document.querySelectorAll('.cat-filter-btn');
  const modal = document.getElementById('catalog-modal');
  const modalTitle = document.getElementById('modal-title');
  const modalPageImg = document.getElementById('modal-page-img');
  const modalPageNum = document.getElementById('modal-page-num');
  const prevBtn = document.getElementById('modal-prev-btn');
  const nextBtn = document.getElementById('modal-next-btn');
  const closeBtn = document.getElementById('modal-close-btn');

  let currentCatalog = null;
  let currentPageIndex = 0;
  let activeCategory = 'all';

  function renderGrid(filterText = '', filterCat = 'all') {
    if (!container) return;
    container.innerHTML = '';

    const filtered = window.CATALOGS_DATA.filter(item => {
      const matchesSearch = item.title.toLowerCase().includes(filterText.toLowerCase()) || 
                            item.category.toLowerCase().includes(filterText.toLowerCase());
      const matchesCat = filterCat === 'all' || item.category === filterCat;
      return matchesSearch && matchesCat;
    });

    if (filtered.length === 0) {
      container.innerHTML = `<div style="grid-column: 1/-1; text-align: center; padding: 4rem 1rem; color: #888;">
        <p style="font-size: 1.2rem; font-weight: 600;">No catalogs found matching your search.</p>
      </div>`;
      return;
    }

    filtered.forEach(item => {
      const card = document.createElement('div');
      card.className = 'catalog-card-item';
      card.style.cssText = 'background: #fff; border-radius: 16px; border: 1px solid rgba(0,0,0,0.08); overflow: hidden; box-shadow: 0 4px 20px rgba(0,0,0,0.04); transition: transform 0.3s ease, box-shadow 0.3s ease; display: flex; flex-direction: column; cursor: pointer;';
      
      card.innerHTML = `
        <div style="position: relative; width: 100%; aspect-ratio: 3/4; background: #f5f5f5; overflow: hidden;">
          <img src="${item.coverImage}" alt="${item.title}" style="width: 100%; height: 100%; object-fit: cover; transition: transform 0.5s ease;">
          <span style="position: absolute; top: 12px; left: 12px; background: rgba(5,26,20,0.85); color: #D4AF37; font-size: 10px; font-weight: 700; text-transform: uppercase; letter-spacing: 0.1em; padding: 4px 10px; border-radius: 20px; backdrop-filter: blur(4px);">${item.category}</span>
          <span style="position: absolute; bottom: 12px; right: 12px; background: rgba(212,175,55,0.95); color: #051a14; font-size: 11px; font-weight: 700; padding: 4px 10px; border-radius: 12px;">📖 ${item.totalPages} Pages</span>
        </div>
        <div style="padding: 1.25rem; flex: 1; display: flex; flex-direction: column; justify-content: space-between;">
          <div>
            <h3 style="font-family: 'Playfair Display', serif; font-size: 1.15rem; font-weight: 700; color: #1a0800; margin-bottom: 6px; line-height: 1.3;">${item.title}</h3>
            <p style="font-size: 0.85rem; color: #666; margin-bottom: 1rem;">${item.subtitle || 'Official Brand Catalog'}</p>
          </div>
          <button class="btn-read-catalog" data-id="${item.id}" style="width: 100%; background: #051a14; color: #D4AF37; border: 1px solid #D4AF37; padding: 10px; border-radius: 8px; font-weight: 700; font-size: 0.9rem; cursor: pointer; transition: background 0.3s ease, color 0.3s ease; text-transform: uppercase; letter-spacing: 0.05em;">
            Read Catalog
          </button>
        </div>
      `;

      card.addEventListener('mouseenter', () => {
        card.style.transform = 'translateY(-6px)';
        card.style.boxShadow = '0 12px 30px rgba(0,0,0,0.12)';
        const img = card.querySelector('img');
        if (img) img.style.transform = 'scale(1.05)';
      });
      card.addEventListener('mouseleave', () => {
        card.style.transform = 'none';
        card.style.boxShadow = '0 4px 20px rgba(0,0,0,0.04)';
        const img = card.querySelector('img');
        if (img) img.style.transform = 'scale(1)';
      });

      card.querySelector('.btn-read-catalog').addEventListener('click', (e) => {
        e.stopPropagation();
        openCatalogModal(item);
      });
      card.addEventListener('click', () => openCatalogModal(item));

      container.appendChild(card);
    });
  }

  function openCatalogModal(catalogItem) {
    currentCatalog = catalogItem;
    currentPageIndex = 0;
    updateModalContent();
    modal.style.display = 'flex';
    document.body.style.overflow = 'hidden';
  }

  function updateModalContent() {
    if (!currentCatalog || !currentCatalog.pages || currentCatalog.pages.length === 0) return;
    modalTitle.textContent = `${currentCatalog.title} (Page ${currentPageIndex + 1} of ${currentCatalog.pages.length})`;
    modalPageImg.src = currentCatalog.pages[currentPageIndex].imageUrl;
    modalPageNum.textContent = `Page ${currentPageIndex + 1} / ${currentCatalog.pages.length}`;
    
    prevBtn.style.opacity = currentPageIndex === 0 ? '0.3' : '1';
    prevBtn.style.pointerEvents = currentPageIndex === 0 ? 'none' : 'auto';
    nextBtn.style.opacity = currentPageIndex === currentCatalog.pages.length - 1 ? '0.3' : '1';
    nextBtn.style.pointerEvents = currentPageIndex === currentCatalog.pages.length - 1 ? 'none' : 'auto';
  }

  if (prevBtn) {
    prevBtn.addEventListener('click', () => {
      if (currentPageIndex > 0) {
        currentPageIndex--;
        updateModalContent();
      }
    });
  }

  if (nextBtn) {
    nextBtn.addEventListener('click', () => {
      if (currentCatalog && currentPageIndex < currentCatalog.pages.length - 1) {
        currentPageIndex++;
        updateModalContent();
      }
    });
  }

  if (closeBtn) {
    closeBtn.addEventListener('click', () => {
      modal.style.display = 'none';
      document.body.style.overflow = 'auto';
    });
  }

  if (modal) {
    modal.addEventListener('click', (e) => {
      if (e.target === modal) {
        modal.style.display = 'none';
        document.body.style.overflow = 'auto';
      }
    });
  }

  if (searchInput) {
    searchInput.addEventListener('input', (e) => {
      renderGrid(e.target.value, activeCategory);
    });
  }

  if (categoryFilters) {
    categoryFilters.forEach(btn => {
      btn.addEventListener('click', () => {
        categoryFilters.forEach(b => {
          b.style.background = 'none';
          b.style.color = '#555';
          b.style.borderColor = 'rgba(0,0,0,0.15)';
        });
        btn.style.background = '#051a14';
        btn.style.color = '#D4AF37';
        btn.style.borderColor = '#D4AF37';
        activeCategory = btn.getAttribute('data-cat');
        renderGrid(searchInput ? searchInput.value : '', activeCategory);
      });
    });
  }

  renderGrid();
});
